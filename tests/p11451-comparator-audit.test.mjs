import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const text=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const json=p=>JSON.parse(text(p));
const audit=json('docs/P11/registro-auditoria-comparador-p11451.json');
test('P11.4.5.1 conserva la preparación aprobada y sus reservas',()=>{
 const reader=json('docs/P11/registro-autorizacion-preparacion-lector-p11425.json');
 assert.equal(audit.phase,'P11.4.5.1');
 assert.deepEqual(audit.scope.editions.map(e=>[e.id,e.candidate,e.books]),reader.editions.map(e=>[e.editionId,e.id,e.books]));
 assert.equal(reader.publicReleaseAuthorized,false);
 assert.equal(reader.corpusImportAuthorized,false);
 assert.equal(reader.scope.alignmentAuthorized,false);
 assert.ok(audit.scope.editions.every(e=>e.readerPreparationApproved&&!e.comparatorPublicationAuthorized));
 assert.equal(audit.scope.historicalCoverage.units,reader.candidate.units);
 assert.equal(audit.scope.historicalCoverage.chapters,reader.candidate.chapters);
 assert.equal(audit.scope.historicalCoverage.emptyMarkers,reader.candidate.emptyMarkers);
 assert.deepEqual(audit.scope.editions.map(e=>e.rights),['public_domain_declared_conditional_territorial_review','CC-BY-4.0']);
});
test('P11.4.5.1 no admite Scrivener ni infiere correspondencias',()=>{
 const registry=json('docs/P9/alineaciones-p931.json');
 assert.equal(registry.publicationAuthorized,false);
 assert.deepEqual(registry.evidence,[]);
 assert.deepEqual(registry.alignments,[]);
 assert.equal(audit.scope.historicalCoverage.verifiedAlignments,registry.alignments.length);
 assert.equal(audit.controls.automaticAlignment,false);
 assert.equal(audit.controls.alignmentEvidenceRequired,true);
 assert.equal(audit.controls.independentNativeReferences,true);
 assert.deepEqual(audit.scope.excluded.map(e=>[e.id,e.status]),[['P1022-R12','pending_specific_file_rights_integrity_admission']]);
 const sources=text('docs/P10/registro-fuentes-p1022.json');
 assert.ok(sources.includes('P1022-R12'));
 assert.ok(sources.includes('licencia del archivo concreto pendiente'));
 const history=text('docs/P9/09-motor-comparacion.md');
 for(const n of [39041,7937,23145])assert.ok(history.includes(String(n)));
});
test('P11.4.5.1 conserva la barrera pública y la compuerta léxica',()=>{
 const page=text('src/pages/biblia/comparador.astro');
 assert.ok(page.includes('createComparatorView(emptyComparatorRelease())'));
 assert.match(page,/<fieldset id="bc-fields" disabled>/);
 const model=text('src/lib/comparator-view.ts');
 assert.ok(model.includes('publicationAuthorized:false,editions:[]'));
 const lexical=json('docs/P11/registro-liberacion-lexicos-p114444.json');
 assert.equal(lexical.status,'blocked_pending_manual_review');
 assert.equal(lexical.canPublish,false);
 assert.equal(lexical.publicationAuthorized,false);
 assert.equal(lexical.exclusions.dodson,'not_included_pending_separate_approval');
 assert.equal(audit.controls.publicComparatorEmpty,true);
 assert.equal(audit.controls.publicCorpus,false);
 assert.equal(audit.controls.publicationAuthorized,false);
 assert.equal(audit.controls.lexicalGateUnchanged,true);
 assert.equal(audit.controls.dodsonExcluded,true);
 assert.equal(audit.controls.manualReviewPending,true);
 assert.deepEqual(audit.progress,lexical.progress);
 assert.equal(audit.next,'P11.4.5.2');
});
